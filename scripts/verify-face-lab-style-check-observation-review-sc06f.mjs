assert.ok(html.includes("file.name!==sample.fileName"));
new Script(html.split("<script>")[1].split("</script>")[0]);
assert.throws(()=>buildStyleCheckLocalObservationReviewHtml({...input,photoCount:9}));
assert.throws(()=>buildStyleCheckLocalObservationReviewHtml({...input,photos:[{fileName:"../secret.jpg",headerReadable:true}]}));
