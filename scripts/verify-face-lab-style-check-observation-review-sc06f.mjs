import assert from "node:assert/strict";
import {Script} from "node:vm";
import {buildStyleCheckLocalObservationReviewHtml} from "./build-face-lab-style-check-observation-review-sc06f.mjs";
const input={status:"preflight_only_not_style_validation",photoCount:2,photos:[{fileName:"test-a.jpg",headerReadable:true},{fileName:"test-b.jpg",headerReadable:false}]};
