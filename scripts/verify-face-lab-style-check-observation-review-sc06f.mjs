const payload=JSON.parse(html.split('id="review-data">')[1].split("</script>")[0]);
assert.equal(payload.photos.length,2);
assert.equal(payload.definitions.length,22);
assert.equal(payload.photos[0].sampleRef,"P01");
assert.ok(html.includes("connect-src 'none'"));
assert.ok(!html.includes("fetch("));
assert.ok(!html.includes("localStorage"));
assert.ok(!html.includes("XMLHttpRequest"));
