import assert from 'node:assert/strict';
import {compareExplicitSkinV2Sessions, SKIN_S3_V2_ADAPTER_VERSION} from './skin-photo-v2-session-adapter.mjs';
const axes = ['oiliness','dehydration','acne','uneven_tone','pores','redness','barrier'];
const conditions = Object.freeze({deviceClass:'device_A',lighting:'controlled',whiteBalance:'neutral',makeup:'none',filter:'none',angle:'front',resolution:'adequate'});
const rows = () => axes.map((axis,i)=>({axis,state:i===0?'not_seen':i===1?'unassessable':'present',value:i===0?0:i===1?null:2,confidence:i===1?'unknown':'high'}));
const make = (id,time,patch={}) => ({observationVersion:'vision-observation-v2',captureId:id,subjectGroupId:'anon_subject_A',capturedAt:time,photoStatus:'available',conditions:{...conditions},skinAnalysisEligible:true,v2Axes:rows(),...patch});
const before=make('a','2026-10-01T13:00:00Z'), after=make('b','2026-10-08T13:00:00Z');
const result=compareExplicitSkinV2Sessions(before,after);
assert.equal(result.adapterVersion,SKIN_S3_V2_ADAPTER_VERSION);
assert.equal(result.status,'comparable');
assert.equal(result.axes.oiliness.beforeEvidenceState,'observed');
assert.equal(result.axes.oiliness.rawScoreDeltaForAudit,0);
assert.equal(result.axes.dehydration.status,'not_comparable');
assert.equal(result.axes.dehydration.rawScoreDeltaForAudit,null);
assert.equal(result.axes.acne.rawScoreDeltaForAudit,0);
assert.equal(result.evidenceBoundary.legacyZeroInferredAsAbsent,false);
assert.equal(result.evidenceBoundary.actualRepeatPhotoStudyCompleted,false);
assert.equal(result.authority.improvementClaimAuthorized,false);
assert.deepEqual(compareExplicitSkinV2Sessions(before,after),result);
// Deliberate explicit absent->present is a research-only delta, never an improvement assertion.
let changed = make('b','2026-10-08T13:00:00Z');
changed.v2Axes[0]={axis:'oiliness',state:'present',value:4,confidence:'high'};
assert.equal(compareExplicitSkinV2Sessions(before,changed).axes.oiliness.rawScoreDeltaForAudit,4);
const bad=(patch)=>assert.throws(()=>compareExplicitSkinV2Sessions(before,make('b',after.capturedAt,patch)));
bad({observationVersion:'vision-observation-v1'});
bad({v2Axes:rows().slice(0,6)});
bad({v2Axes:[...rows().slice(0,6),rows()[0]]});
bad({v2Axes:rows().map((r,i)=>i===0?{...r,value:null}:r)});
bad({v2Axes:rows().map((r,i)=>i===0?{...r,state:'unknown',value:0,confidence:'unknown'}:r)});
bad({v2Axes:rows().map((r,i)=>i===1?{...r,state:'unassessable',value:0}:r)});
bad({v2Axes:rows().map((r,i)=>i===1?{...r,state:'unknown',value:null,confidence:'medium'}:r)});
bad({v2Axes:rows().map((r,i)=>i===2?{...r,state:'present',value:0}:r)});
bad({v2Axes:rows().map((r,i)=>i===2?{...r,freeText:'private'}:r)});
bad({v2Axes:rows().map((r,i)=>i===2?{...r,axis:'uv'}:r)});
bad({photoStatus:'ineligible'});
bad({skinAnalysisEligible:false});
bad({faceLabEligible:false});
bad({photoUrl:'https://example.org/private.jpg'});
bad({v2Axes: [{axis:'acne',score:0},...rows().slice(1)]});
const ineligible=make('b',after.capturedAt,{skinAnalysisEligible:false,photoStatus:'ineligible',v2Axes:[]});
const stop=compareExplicitSkinV2Sessions(before,ineligible);
assert.equal(stop.status,'not_comparable');
assert.equal(stop.axes.oiliness.rawScoreDeltaForAudit,null);
assert(stop.reasonCodes.includes('photo_not_available'));
const different=compareExplicitSkinV2Sessions(before,make('b',after.capturedAt,{subjectGroupId:'anon_subject_B'}));
assert.equal(different.status,'not_comparable');
assert(different.reasonCodes.includes('different_subject_group'));
const filtered=compareExplicitSkinV2Sessions(before,make('b',after.capturedAt,{conditions:{...conditions,filter:'present'}}));
assert.equal(filtered.status,'not_comparable');
const low=make('b',after.capturedAt);
low.v2Axes[0]={axis:'oiliness',state:'not_seen',value:0,confidence:'low'};
assert.equal(compareExplicitSkinV2Sessions(before,low).axes.oiliness.rawScoreDeltaForAudit,null);
assert.equal(compareExplicitSkinV2Sessions(before,low).axes.oiliness.status,'not_comparable');
console.log('verify-face-lab-skin-s3-v2-adapter: PASS (synthetic only, explicit v2 state, zero legacy inference)');
