#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {fileURLToPath} from "node:url";

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const P="evidence/product-fact-subject-coverage-v1/trust-p16-skin1004-uv-market-formulation-source-recovery-v1.json";
const P6="evidence/product-fact-subject-coverage-v1/trust-p6-sunscreen-product-fact-subject-coverage-v1.json";
const P6_BLOB="1917e4140a2ddc8a8a26a2c3c8b139c137a176f2";
const stable=v=>Array.isArray(v)?v.map(stable):v&&typeof v==="object"?Object.fromEntries(Object.keys(v).sort().map(k=>[k,stable(v[k])])):v;
const canonical=v=>JSON.stringify(stable(v));
const digest=v=>crypto.createHash("sha256").update(typeof v==="string"?v:canonical(v)).digest("hex");
const gitBlob=p=>execFileSync("git",["hash-object",p],{cwd:ROOT,encoding:"utf8"}).trim();

assert.equal(gitBlob(P6),P6_BLOB,"P6 authority blob drift");
const p6=JSON.parse(fs.readFileSync(path.join(ROOT,P6),"utf8"));
const prior=p6.uncovered_products.find(x=>x.product_id==="fdf06871-db8e-4e73-a48c-c057c5ce925d");
assert.ok(prior,"P6 SKIN1004 row missing");
assert.equal(prior.status,"MARKET_FORMULATION_SCOPE_REVIEW_REQUIRED");
const x=JSON.parse(fs.readFileSync(path.join(ROOT,P),"utf8"));
const {research_content_sha256,...body}=x;
assert.equal(digest(body),research_content_sha256,"research content digest");
assert.equal(x.stage,"TRUST-P16");
assert.equal(x.phase,"RESEARCH_ONLY_MARKET_FORMULATION_AND_FACT_SOURCE_RECOVERY");
assert.equal(x.target.product_id,"fdf06871-db8e-4e73-a48c-c057c5ce925d");
assert.equal(x.target.catalog_name_en,"Hyalu-Cica Water-Fit Sun Serum UV");
assert.equal(x.production_prestate.subject_count,0);
assert.equal(x.production_prestate.current_count,0);
assert.equal(x.production_prestate.official_source_locator_rows,0);
assert.deepEqual(x.production_prestate.global_counts,{subjects:21,sources:22,bindings:22,evidence:51,fact_instances:51,evidence_links:51,review_assignments:51,confirmations:51,current:51});
assert.equal(x.registry_constraints.spf_value.market_required,true);
assert.equal(x.registry_constraints.uva_label.broad_spectrum_allowed,false);
assert.deepEqual(x.registry_constraints.uva_label.allowed_values,["PA+","PA++","PA+++","PA++++","UVA-PF-declared"]);
const uv=x.first_party_sources.find(s=>s.role==="exact_uv_identity_and_partial_fact_source");
const nonuv=x.first_party_sources.find(s=>s.role==="distinct_non_uv_formulation_exclusion");
assert.ok(uv&&nonuv);
assert.equal(uv.current_observation.name,"Hyalu-Cica Water-Fit Sun Serum UV");
assert.equal(uv.current_observation.size_ml,50);
assert.equal(uv.current_observation.direct_spf_claim,"SPF50 broad-spectrum coverage");
assert.equal(uv.market_scope_explicit_in_reviewed_body,false);
assert.equal(uv.machine_verifiable_spf_support,true);
assert.equal(uv.machine_verifiable_registry_uva_support,false);
assert.equal(nonuv.current_observation.name,"Hyalu-Cica Water-Fit Sun Serum");
assert.deepEqual(nonuv.current_observation.direct_claims,["SPF50+","PA++++"]);
assert.equal(nonuv.positive_fact_support_for_uv_target,false);
assert.equal(x.formulation_adjudication.result,"DISTINCT_FORMULATIONS");
assert.equal(x.formulation_adjudication.cross_formula_pa_transfer_prohibited,true);
assert.equal(x.fact_recovery.spf_value.raw_claim,"SPF50");
assert.equal(x.fact_recovery.spf_value.value_number,50);
assert.deepEqual(x.fact_recovery.spf_value.qualifier,{plus_modifier:"none"});
assert.equal(x.fact_recovery.spf_value.status,"RECOVERED_VALUE_MARKET_SCOPE_BLOCKED");
assert.equal(x.fact_recovery.uva_label.registry_admissible,false);
assert.equal(x.fact_recovery.uva_label.non_uv_pa_transfer_allowed,false);
assert.equal(x.adjudication.result,"PARTIAL_FACT_SOURCE_RECOVERY_MARKET_SCOPE_BLOCKED");
assert.equal(x.adjudication.production_write_authorized,false);
assert.equal(x.invariants.hosted_product_fact_writes,0);
assert.equal(x.invariants.direct_product_fact_dml,false);
assert.equal(x.invariants.subject_registration_performed,false);
assert.equal(x.invariants.catalog_fact_fields_used_as_product_fact_authority,false);
assert.equal(x.invariants.broad_spectrum_to_pa_conversion,false);
assert.equal(x.invariants.cross_formula_pa_transfer,false);
console.log(JSON.stringify({ok:true,stage:x.stage,result:x.adjudication.result,research_content_sha256},null,2));
