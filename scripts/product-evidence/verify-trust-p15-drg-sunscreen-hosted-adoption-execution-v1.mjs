#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {fileURLToPath} from "node:url";

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const P="evidence/product-fact-adoption-v1/trust-p15-drg-sunscreen-hosted-adoption-execution-v1.json";
const PLAN="evidence/product-fact-adoption-v1/trust-p15-drg-sunscreen-hosted-adoption-plan-v1.json";
const PLAN_BLOB="d2fa47268ca8ed796a4015d2034a8676952c2634";
const PLAN_SHA="d515a8172644aa727ef836ed5ec68e69e5d73e73dbe369141d45154a9473e0a4";
const stable=v=>Array.isArray(v)?v.map(stable):v&&typeof v==="object"?Object.fromEntries(Object.keys(v).sort().map(k=>[k,stable(v[k])])):v;
const canonical=v=>JSON.stringify(stable(v));
const digest=v=>crypto.createHash("sha256").update(typeof v==="string"?v:canonical(v)).digest("hex");
const gitBlob=p=>execFileSync("git",["hash-object",p],{cwd:ROOT,encoding:"utf8"}).trim();

assert.equal(gitBlob(PLAN),PLAN_BLOB,"P15 plan blob drift");
const plan=JSON.parse(fs.readFileSync(path.join(ROOT,PLAN),"utf8"));
assert.equal(plan.plan_content_sha256,PLAN_SHA,"P15 plan digest drift");
const x=JSON.parse(fs.readFileSync(path.join(ROOT,P),"utf8"));
const {execution_content_sha256,...body}=x;
assert.equal(digest(body),execution_content_sha256,"execution content digest");
assert.equal(x.status,"PRODUCTION_CONFIRMED");
assert.equal(x.authority.p15_plan_merge_sha,"26407faea37effd2ecb730c35d23ad9808eb6fc8");
assert.equal(x.authority.p15_plan_blob_sha,PLAN_BLOB);
assert.equal(x.execution_policy.controlled_rpc_only,true);
assert.equal(x.execution_policy.direct_product_fact_table_dml,false);
assert.equal(x.execution_policy.all_planned_preflights_ready_before_any_confirm,true);
assert.equal(x.execution_policy.both_confirms_same_sql_transaction,true);
assert.deepEqual(x.expected_delta,{subjects:1,sources:1,bindings:1,evidence:2,fact_instances:2,evidence_links:2,review_assignments:2,confirmations:2,current:2});
assert.equal(x.poststate.subjects-x.prestate.subjects,1);
assert.equal(x.poststate.sources-x.prestate.sources,1);
assert.equal(x.poststate.bindings-x.prestate.bindings,1);
assert.equal(x.poststate.evidence-x.prestate.evidence,2);
assert.equal(x.poststate.fact_instances-x.prestate.fact_instances,2);
assert.equal(x.poststate.evidence_links-x.prestate.evidence_links,2);
assert.equal(x.poststate.review_assignments-x.prestate.review_assignments,2);
assert.equal(x.poststate.confirmations-x.prestate.confirmations,2);
assert.equal(x.poststate.current-x.prestate.current,2);
assert.equal(x.poststate.target_subjects,1);
assert.equal(x.poststate.target_spf_current,1);
assert.equal(x.poststate.target_uva_current,1);
assert.equal(x.subject.subject_semantic_key,plan.subjects[0].subject_semantic_key);
assert.equal(x.source_binding.source_content_digest,plan.sources[0].content_digest);
assert.equal(x.source_binding.binding_state,"equivalent_presentation_match");
assert.equal(x.source_binding.scope_relation,"equivalent");
assert.equal(x.facts.length,2);
const spf=x.facts.find(f=>f.fact_key==="spf_value");
const uva=x.facts.find(f=>f.fact_key==="uva_label");
assert.ok(spf&&uva);
assert.equal(spf.proposition_key,plan.propositions.find(p=>p.fact_key==="spf_value").proposition_key);
assert.equal(spf.canonical_evidence_digest,plan.propositions.find(p=>p.fact_key==="spf_value").canonical_evidence_digest);
assert.equal(spf.preflight.status,"ready");
assert.equal(spf.assignment_state,"confirmed");
assert.equal(spf.value_number,50);
assert.deepEqual(spf.qualifier,{plus_modifier:"plus"});
assert.equal(uva.proposition_key,plan.propositions.find(p=>p.fact_key==="uva_label").proposition_key);
assert.equal(uva.canonical_evidence_digest,plan.propositions.find(p=>p.fact_key==="uva_label").canonical_evidence_digest);
assert.equal(uva.preflight.status,"ready");
assert.equal(uva.assignment_state,"confirmed");
assert.equal(uva.value_enum,"PA++++");
assert.equal(x.closure.p15_phase_b,"CONFIRMED");
assert.equal(x.closure.drg_green_mild_up_sun_plus_coverage,"SPF_AND_UVA_CURRENT");
console.log(JSON.stringify({ok:true,stage:x.stage,status:x.status,execution_content_sha256},null,2));
