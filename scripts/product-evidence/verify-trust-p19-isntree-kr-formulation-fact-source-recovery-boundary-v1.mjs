#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import {fileURLToPath} from "node:url";

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const P="evidence/product-fact-subject-coverage-v1/trust-p19-isntree-kr-formulation-fact-source-recovery-boundary-v1.json";
const stable=v=>Array.isArray(v)?v.map(stable):v&&typeof v==="object"?Object.fromEntries(Object.keys(v).sort().map(k=>[k,stable(v[k])])):v;
const canonical=v=>JSON.stringify(stable(v));
const digest=v=>crypto.createHash("sha256").update(typeof v==="string"?v:canonical(v)).digest("hex");

const x=JSON.parse(fs.readFileSync(path.join(ROOT,P),"utf8"));
const {research_content_sha256,...body}=x;
assert.equal(digest(body),research_content_sha256,"research content digest");
assert.equal(x.version,"trust-p19-isntree-kr-formulation-fact-source-recovery-boundary-v1");
assert.equal(x.stage,"TRUST-P19");
assert.equal(x.phase,"RESEARCH_ONLY_KR_FORMULATION_FACT_SOURCE_RECOVERY_BOUNDARY");
assert.equal(x.authority.source_main_sha,"601d745047da159f66db636caa54a42c853dd1c4");
assert.equal(x.target.product_id,"336bb533-0fe4-4380-8b9f-ab16fb24b807");
assert.equal(x.target.size_ml,50);
assert.equal(x.production_prestate.subject_count,0);
assert.equal(x.production_prestate.current_count,0);
assert.deepEqual(x.production_prestate.global_counts,{subjects:22,sources:23,bindings:23,evidence:52,fact_instances:52,evidence_links:52,review_assignments:52,confirmations:52,current:52});
const kr=x.first_party_sources.find(s=>s.role==="exact_kr_market_product_presence");
const global=x.first_party_sources.find(s=>s.role==="exact_global_product_formula_context_not_kr_formula_bridge");
assert.ok(kr&&global);
assert.equal(kr.market,"KR");
assert.equal(kr.current_observation.name,"히아루론산 워터리 선 젤 50ml");
assert.equal(kr.current_observation.size_ml,50);
assert.equal(kr.current_observation.domestic_delivery_visible,true);
assert.equal(kr.current_observation.machine_readable_spf_claim,null);
assert.equal(kr.current_observation.machine_readable_pa_claim,null);
assert.equal(kr.current_observation.machine_readable_full_ingredients,false);
assert.equal(global.current_observation.ingredient_count,43);
assert.equal(global.current_observation.ingredient_order_sha256,"8b8523b0f2379fb8815723a49b6afb793a2c64aab24ee487730635e85556c0eb");
assert.equal(global.current_observation.machine_readable_spf_claim,null);
assert.equal(global.current_observation.machine_readable_pa_claim,null);
assert.equal(x.market_adjudication.kr_exact_product_presence,"RECOVERED");
assert.equal(x.market_adjudication.kr_subject_market_applicability,"NOT_YET_FREEZABLE_WITHOUT_FORMULATION_IDENTITY");
assert.equal(x.market_adjudication.global_page_not_transferable_to_kr_subject,true);
assert.equal(x.formulation_adjudication.status,"NOT_ESTABLISHED_FOR_KR_SUBJECT");
assert.equal(x.formulation_adjudication.same_formulation_bridge_established,false);
assert.equal(x.formulation_adjudication.cross_market_formula_transfer_allowed,false);
assert.equal(x.fact_recovery.spf_value.status,"NOT_RECOVERED_FROM_ADMISSIBLE_FIRST_PARTY_DIRECT_CLAIM");
assert.equal(x.fact_recovery.uva_label.status,"NOT_RECOVERED_FROM_ADMISSIBLE_FIRST_PARTY_DIRECT_CLAIM");
assert.equal(x.fact_recovery.uva_label.pa_inference_allowed,false);
assert.equal(x.adjudication.production_write_authorized,false);
assert.equal(x.adjudication.subject_registration_authorized,false);
assert.equal(x.adjudication.fact_ingest_authorized,false);
assert.equal(x.adjudication.next_gate,"FIRST_PARTY_KR_FORMULATION_OR_DIRECT_SPF_PA_SOURCE_RECOVERY_REQUIRED");
assert.equal(x.invariants.hosted_product_fact_writes,0);
assert.equal(x.invariants.direct_product_fact_dml,false);
assert.equal(x.invariants.cross_market_formula_transfer,false);
assert.equal(x.invariants.spf_inference,false);
assert.equal(x.invariants.pa_inference,false);
console.log(JSON.stringify({ok:true,stage:x.stage,result:x.adjudication.result,research_content_sha256},null,2));
