#!/usr/bin/env node
import fs from "node:fs";
import assert from "node:assert/strict";
import {
  VERSION, STAGE, AXIS_KEY, CONTRACT_MODE, PRIMARY_TERMINAL_OUTCOME,
  ACTIVE_IDENTITIES_V1, OUTPUTS, buildAll, canonicalJson,
} from "./exfoliation-non-numeric-pda-contract-v1.mjs";

let assertions = 0;
function eq(actual, expected, message) { assert.deepEqual(actual, expected, message); assertions += 1; }
function ok(value, message) { assert.ok(value, message); assertions += 1; }
function includes(array, value, message) { ok(array.includes(value), message || `missing ${value}`); }

const A = buildAll();
const B = buildAll();
for (const key of ["contract", "examples", "replay"]) eq(canonicalJson(A[key]), canonicalJson(B[key]), `${key} Build A/B drift`);
eq(A.doc, B.doc, "docs Build A/B drift");
for (const [key, rel] of Object.entries(OUTPUTS)) {
  const checked = fs.readFileSync(rel, "utf8");
  eq(checked, A.rendered[key], `${rel} != canonical generated bytes`);
}

const c = A.contract;
const e = A.examples;
const r = A.replay;

// 1-3 authority/stage/upstream
eq(c.stage, "V2.1-8O", "stage");
eq(c.axis_key, "exfoliation_load", "axis");
eq(c.authority.v21_8n_primary_outcome, "NON_NUMERIC_DECISION_REPRESENTATION_RECOMMENDED", "8N outcome drift");

// 4-7 exact non-numeric mode
eq(c.contract_mode, "STRUCTURED_CATEGORICAL", "contract mode");
eq(c.output_contract.numeric_estimate, null, "numeric estimate must be null");
eq(c.output_contract.ordinal_magnitude, null, "ordinal magnitude must be null");
eq(c.output_contract.potency_order, null, "potency ordering must be absent/null");

// 8-10 identity/multi-active/cardinality
eq(c.applicability.active_identity_mapping_values_v1, ["lactic_acid", "mandelic_acid", "salicylic_acid"], "v1 identities");
eq(c.output_contract.active_identity_set.semantic_ordering, "NONE", "active identity semantic ordering");
eq(c.multi_active_contract.rule, "MULTI_ACTIVE_CARDINALITY_IS_NOT_POTENCY", "multi-active rule");
eq(c.multi_active_contract.first_active_wins, false); eq(c.multi_active_contract.highest_concentration_wins, false); eq(c.multi_active_contract.sum_mean_max, false);
includes(c.output_object_invariants, "ACTIVE_COUNT_IS_NOT_POTENCY");

// 11-14 context never becomes magnitude
for (const [key, item] of Object.entries(c.context_contract)) eq(item.magnitude_contribution, "NO", `${key} magnitude contribution`);
eq(c.context_contract.active_concentration.lineage, "MUST_MATCH_RELEVANT_CONTAINS_ACTIVE_PARENT_PROPOSITION");
eq(c.context_contract.active_concentration.missingness, "MISSING_REMAINS_MISSING_NEVER_ZERO");
includes(c.output_object_invariants, "FREQUENCY_IS_NOT_EFFICACY");
includes(c.output_object_invariants, "PAD_TEXTURE_IS_NOT_MAGNITUDE");
includes(c.output_object_invariants, "WIPE_OFF_IS_NOT_POTENCY");

// 15-18 missingness, negative, identity block, context role
eq(c.missingness_contract.missing_current, "GOVERNED_SIGNAL_UNKNOWN_NOT_FALSE");
eq(c.negative_signal_contract.explicit_negative_signal_supported_in_v1, false, "v1 must not invent negative signal");
ok(c.negative_signal_contract.reason.includes("entity_identifier"), "negative rule must be grounded in contains_active value type");
eq(c.missingness_contract.identity_blocked, "GOVERNED_SIGNAL_BLOCKED");
for (const item of Object.values(c.context_contract)) eq(item.role, "CONTEXT_ONLY");

// 19-23 product/downstream/provenance/legacy
const excluded = c.downstream_boundary.intrinsic_pda_excludes;
includes(excluded, "user sensitivity");
includes(excluded, "routine overlap");
includes(excluded, "recent user reaction");
includes(excluded, "final recommendation decision");
eq(c.downstream_boundary.direct_fact_to_score, "PROHIBITED");
const provenanceFields = c.provenance_contract.minimum_provenance_fields;
for (const field of ["subject_id","fact_instance_id","confirmation_id","proposition_key","fact_key","semantic_status","authority_ceiling","fused_confidence"]) includes(provenanceFields, field);
eq(c.legacy_boundary.relationship, "LEGACY_NOT_AUTHORITY_FOR_NEW_CONTRACT");
eq(c.legacy_boundary.equivalence_claimed, false);

// 24-27 no registry/Hosted/numeric/prod changes
eq(c.explicit_non_actions.registry_definition_delta_v21_8o, 0); eq(c.explicit_non_actions.hosted_product_fact_writes_v21_8o, 0); eq(c.explicit_non_actions.numeric_fitting_v21_8o, 0); eq(c.explicit_non_actions.pda_production_consumption_v21_8o, 0); eq(c.production_status.recommendation_activation, "NO"); eq(c.production_status.recommendation_behavior_delta, 0);

// 28 deterministic examples and required coverage
eq(e.examples.length, 4, "four deterministic examples required");
const byId = Object.fromEntries(e.examples.map((x) => [x.example_id, x]));
for (const x of e.examples) {
  eq(x.expected_output.numeric_estimate, null, `${x.example_id} numeric`);
  eq(x.expected_output.ordinal_magnitude, null, `${x.example_id} ordinal`);
  eq(x.expected_output.potency_order, null, `${x.example_id} potency`);
  eq(x.expected_output.active_identities.semantic_ordering, "NONE", `${x.example_id} identity order`);
}
eq(byId.single_active_with_concentration_context.expected_output.active_identities.items.map((x) => x.identity), ["mandelic_acid"]);
eq(byId.single_active_missing_concentration.expected_output.uncertainty.reasons.includes("ACTIVE_CONCENTRATION_MISSING"), true);
eq(byId.multi_active_with_pad_context.expected_output.active_identities.items.map((x) => x.identity), ["lactic_acid", "salicylic_acid"]);
eq(byId.multi_active_with_pad_context.expected_output.multi_active_status, "multiple");
eq(byId.no_v1_relevant_signal_with_context.expected_output.signal_status, "GOVERNED_SIGNAL_NOT_ESTABLISHED");
eq(byId.no_v1_relevant_signal_with_context.expected_output.active_identities.items, []);
includes(byId.no_v1_relevant_signal_with_context.expected_output.uncertainty.reasons, "NEGATIVE_SIGNAL_NOT_AUTHORIZED");
eq(byId.no_v1_relevant_signal_with_context.expected_output.non_axis_contains_active_identities.map((x) => x.identity), ["hyaluronic_acid", "sodium_dna"]);

// 29-30 Build A/B + checked-in equality asserted above.
// 31 exactly one terminal outcome
eq(c.primary_terminal_outcome, PRIMARY_TERMINAL_OUTCOME);
const terminalOutcomeFields = Object.entries(c).filter(([key]) => key === "primary_terminal_outcome");
eq(terminalOutcomeFields.length, 1, "exactly one primary terminal outcome field");

// Applicability/versioning / unsupported identity safety
eq(c.applicability.categories, ["toner_essence", "toner_pad", "treatment"]);
eq(c.applicability.active_identity_mapping_exhaustive_forever, false);
eq(c.applicability.active_identity_mapping_version, "exfoliating-active-identity-set-v1");
eq(new Set(ACTIVE_IDENTITIES_V1).size, ACTIVE_IDENTITIES_V1.length);
eq(c.missingness_contract.outside_mapper_identity_set, "PRESERVE_AS_NON_AXIS_IDENTITY_NO_SILENT_MAPPING");

// Context registry-scope transcription
eq(c.context_contract.product_format.applicable_categories, ["toner_essence", "toner_pad"]);
eq(c.context_contract.wipe_off_use.applicable_categories, ["toner_essence", "toner_pad"]);
eq(c.context_contract.pad_surface_texture.applicable_categories, ["toner_pad"]);
eq(c.context_contract.active_concentration.cardinality, "many");
eq(c.context_contract.recommended_use_frequency.value_type, "range_unit");

// Downstream ledger mapping exact 15 requirements and legacy split
eq(c.downstream_boundary.downstream_requirement_mapping.length, 15);
eq(new Set(c.downstream_boundary.downstream_requirement_mapping.map((x) => x.requirement_id)).size, 15);
eq(c.downstream_boundary.downstream_requirement_mapping.find((x) => x.requirement_id === "R14").disposition, "LEGACY_NOT_AUTHORITY_FOR_NEW_CONTRACT");
eq(c.downstream_boundary.downstream_requirement_mapping.find((x) => x.requirement_id === "R06").disposition, "COMPARATOR_NOT_ESTABLISHED");
eq(c.downstream_boundary.downstream_requirement_mapping.find((x) => x.requirement_id === "R15").disposition, "NOT_ESTABLISHED");

// Historical replay lineage and expected zero production delta
eq(r.historical_lineage.map((x) => x.outcome), [
  "STRUCTURALLY_READY_FOR_BOUNDED_OFFLINE_CALIBRATION",
  "NUMERIC_ANCHOR_GAP_CONFIRMED",
  "NUMERIC_ANCHOR_EVIDENCE_CONTRACT_DESIGNED",
  "NO_NUMERIC_ANCHOR_SOURCE_FOUND",
  "NON_NUMERIC_DECISION_REPRESENTATION_RECOMMENDED",
]);
eq(r.historical_artifact_rewrite, false);
eq(r.production_invariance_expected.evaluations, 1968);
for (const field of ["score_delta","ranking_delta","top1_delta","top3_delta","eligibility_delta","public_response_delta","persistence_delta","candidate_policy_delta"]) eq(r.production_invariance_expected[field], 0, field);
eq(r.production_invariance_expected.pda_production_consumption, "NO");
eq(r.production_invariance_expected.recommendation_activation, "NO");

// Explicit stage closeout semantics
eq(VERSION, "exfoliation-non-numeric-pda-contract-v1"); eq(STAGE, "V2.1-8O"); eq(AXIS_KEY, "exfoliation_load"); eq(CONTRACT_MODE, "STRUCTURED_CATEGORICAL");
eq(c.next_stage_recommendation.stage, "Exfoliation Non-Numeric PDA Offline/Shadow Implementation & Replay");
eq(c.next_stage_recommendation.status, "RECOMMENDED_NOT_EXECUTED");

console.log(JSON.stringify({ version: "verify-exfoliation-non-numeric-pda-contract-v1", status: "PASS", assertions, stage: STAGE, axis_key: AXIS_KEY, primary_terminal_outcome: PRIMARY_TERMINAL_OUTCOME, hashes: A.hashes }));
