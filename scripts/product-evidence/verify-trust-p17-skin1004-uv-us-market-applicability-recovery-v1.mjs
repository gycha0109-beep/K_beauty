#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {fileURLToPath} from "node:url";

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const P="evidence/product-fact-subject-coverage-v1/trust-p17-skin1004-uv-us-market-applicability-recovery-v1.json";
const P16="evidence/product-fact-subject-coverage-v1/trust-p16-skin1004-uv-market-formulation-source-recovery-v1.json";
const P16_BLOB="5381536524a4aea0faac3451b895a2d2fc5531f6";
const stable=v=>Array.isArray(v)?v.map(stable):v&&typeof v==="object"?Object.fromEntries(Object.keys(v).sort().map(k=>[k,stable(v[k])])):v;
const canonical=v=>JSON.stringify(stable(v));
const digest=v=>crypto.createHash("sha256").update(typeof v==="string"?v:canonical(v)).digest("hex");
const gitBlob=p=>execFileSync("git",["hash-object",p],{cwd:ROOT,encoding:"utf8"}).trim();

assert.equal(gitBlob(P16),P16_BLOB,"P16 authority blob drift");
const p16=JSON.parse(fs.readFileSync(path.join(ROOT,P16),"utf8"));
assert.equal(p16.adjudication.result,"PARTIAL_FACT_SOURCE_RECOVERY_MARKET_SCOPE_BLOCKED");
assert.equal(p16.fact_recovery.spf_value.value_number,50);
assert.deepEqual(p16.fact_recovery.spf_value.qualifier,{plus_modifier:"none"});
const x=JSON.parse(fs.readFileSync(path.join(ROOT,P),"utf8"));
const {research_content_sha256,...body}=x;
assert.equal(digest(body),research_content_sha256,"research content digest");
assert.equal(x.stage,"TRUST-P17");
assert.equal(x.phase,"RESEARCH_ONLY_US_MARKET_APPLICABILITY_RECOVERY");
assert.equal(x.target.product_id,"fdf06871-db8e-4e73-a48c-c057c5ce925d");
assert.equal(x.production_prestate.subject_count,0);
assert.equal(x.production_prestate.current_count,0);
assert.deepEqual(x.production_prestate.global_counts,{subjects:21,sources:22,bindings:22,evidence:51,fact_instances:51,evidence_links:51,review_assignments:51,confirmations:51,current:51});
assert.equal(x.market_adjudication.result,"US_MARKET_APPLICABILITY_RECOVERED");
assert.equal(x.market_adjudication.market_applicability,"US");
assert.equal(x.market_adjudication.kr_market_applicability_recovered,false);
assert.equal(x.market_adjudication.global_market_applicability_recovered,false);
assert.equal(x.market_adjudication.market_scope_transfer_beyond_us_prohibited,true);
const product=x.first_party_us_sources.find(s=>s.role==="exact_us_market_product_and_spf_source");
const directory=x.first_party_us_sources.find(s=>s.role==="us_market_context_authority");
assert.ok(product&&directory);
assert.equal(product.market,"US");
assert.equal(product.current_observation.name,"Hyalu-Cica Water-Fit Sun Serum UV");
assert.equal(product.current_observation.size_ml,50);
assert.equal(product.current_observation.direct_spf_claim,"SPF50 broad-spectrum coverage");
assert.equal(product.current_observation.active_ingredient_order_sha256,"c739c0ae4b3250451185c0f867adb4b23e73c368648f26546c1b1f7440bbd04f");
assert.equal(directory.market,"US");
assert.equal(directory.current_observation.country_region,"US");
assert.equal(x.fact_recovery.spf_value.status,"RECOVERED_SUPPORTED_FOR_US_SCOPE");
assert.equal(x.fact_recovery.spf_value.value_number,50);
assert.deepEqual(x.fact_recovery.spf_value.qualifier,{plus_modifier:"none"});
assert.equal(x.fact_recovery.spf_value.market,"US");
assert.equal(x.fact_recovery.uva_label.status,"REGISTRY_BLOCKED");
assert.equal(x.fact_recovery.uva_label.registry_admissible,false);
assert.equal(x.fact_recovery.uva_label.pa_inference_allowed,false);
assert.equal(x.fact_recovery.uva_label.non_uv_pa_transfer_allowed,false);
assert.equal(x.adjudication.result,"US_MARKET_APPLICABILITY_AND_SPF_SOURCE_RECOVERED");
assert.equal(x.adjudication.production_write_authorized,false);
assert.equal(x.adjudication.next_gate,"SEPARATE_DETERMINISTIC_US_SPF_HOSTED_ADOPTION_PLAN");
assert.equal(x.invariants.hosted_product_fact_writes,0);
assert.equal(x.invariants.direct_product_fact_dml,false);
assert.equal(x.invariants.kr_scope_inference,false);
assert.equal(x.invariants.global_scope_inference,false);
assert.equal(x.invariants.broad_spectrum_to_pa_conversion,false);
assert.equal(x.invariants.cross_formula_pa_transfer,false);
console.log(JSON.stringify({ok:true,stage:x.stage,result:x.adjudication.result,research_content_sha256},null,2));
