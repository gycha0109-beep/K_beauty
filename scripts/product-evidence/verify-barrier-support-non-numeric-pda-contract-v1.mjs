#!/usr/bin/env node
import fs from "node:fs";
import assert from "node:assert/strict";
import {
  VERSION,STAGE,AXIS_KEY,CONTRACT_MODE,PRIMARY_TERMINAL_OUTCOME,
  SIGNAL_STATES,OUTPUTS,buildAll,canonicalJson,mapBarrierSupportNonNumericPda
} from "./barrier-support-non-numeric-pda-contract-v1.mjs";

let assertions=0;
function eq(actual,expected,message){assert.deepEqual(actual,expected,message);assertions+=1;}
function ok(value,message){assert.ok(value,message);assertions+=1;}
function includes(array,value,message){ok(array.includes(value),message||`missing ${value}`);}

const A=buildAll();
const B=buildAll();
for(const key of ["contract","examples","replay"]) eq(canonicalJson(A[key]),canonicalJson(B[key]),`${key} Build A/B drift`);
eq(A.doc,B.doc,"docs Build A/B drift");
for(const [key,rel] of Object.entries(OUTPUTS)){
  const checked=fs.readFileSync(rel,"utf8");
  eq(checked,A.rendered[key],`${rel} != canonical generated bytes`);
}

const c=A.contract;
const e=A.examples;
const r=A.replay;
const r2=JSON.parse(fs.readFileSync("evidence/product-decision-axis-feasibility-v2/barrier-support-non-numeric-shadow-feasibility-v1.json","utf8"));
const r2Corpus=JSON.parse(fs.readFileSync("evidence/product-decision-axis-feasibility-v2/barrier-support-shadow-feasibility-corpus-v1.json","utf8"));
const registry=JSON.parse(fs.readFileSync("evidence/product-evidence-decision-axis-v1/cross-category-registry-v1.json","utf8"));
const historicalMapper=fs.readFileSync("scripts/product-evidence/product-decision-axis-cross-category-v1.mjs","utf8");
const historicalResolver=fs.readFileSync("scripts/product-evidence/product-fact-current-resolver-v1.mjs","utf8");

eq(VERSION,"barrier-support-non-numeric-pda-contract-v1");
eq(STAGE,"V2.1-8H-R3");
eq(AXIS_KEY,"barrier_support");
eq(CONTRACT_MODE,"STRUCTURED_CATEGORICAL");
eq(PRIMARY_TERMINAL_OUTCOME,"NON_NUMERIC_BARRIER_SUPPORT_PDA_CONTRACT_FROZEN");
eq(c.primary_terminal_outcome,PRIMARY_TERMINAL_OUTCOME);
eq(c.authority.r2_terminal_outcome,"BARRIER_SUPPORT_NON_NUMERIC_SHADOW_FEASIBLE_CONTRACT_REQUIRED");
eq(r2.terminal_outcome,"BARRIER_SUPPORT_NON_NUMERIC_SHADOW_FEASIBLE_CONTRACT_REQUIRED");
eq(r2.execute_next_gate_now,false);

const claimDef=registry.facts.find(x=>x.fact_key==="barrier_support_claim");
const roleDef=registry.facts.find(x=>x.fact_key==="primary_use_role");
ok(claimDef&&roleDef,"Registry definitions required");
eq(claimDef.value_type,"boolean");
eq(claimDef.negative_evidence_requirement,"explicit_negative_only");
eq(claimDef.semantic_definition,"Official barrier-support claim; distinct from measured barrier improvement.");
eq(roleDef.semantic_definition,"Declared or reviewed primary usage role; role is not recommendation policy.");

eq(c.output_contract.numeric_estimate,null);
eq(c.output_contract.ordinal_magnitude,null);
eq(c.output_contract.effect_strength,null);
eq(c.input_contract.context_fact.magnitude_contribution,"NO");
eq(c.input_contract.context_fact.signal_truth_contribution,"NO");
eq(c.legacy_boundary.direct_fact_to_score,"PROHIBITED");
eq(c.legacy_boundary.direct_fact_to_rank,"PROHIBITED");
eq(c.output_contract.production_consumption,"NO");
eq(c.production_status.recommendation_activation,"NO");
eq(c.production_status.public_activation,"NO");
eq(c.production_status.production_cutover,"NO");

eq(SIGNAL_STATES,c.state_machine.signal_state_enum);
includes(c.output_object_invariants,"SUPPORTED_TRUE_IS_DISTINCT_FROM_SUPPORTED_FALSE");
includes(c.output_object_invariants,"SUPPORTED_FALSE_REQUIRES_EXPLICIT_GOVERNED_FALSE_CURRENT");
includes(c.output_object_invariants,"MISSING_IS_NOT_FALSE");
includes(c.output_object_invariants,"INSUFFICIENT_IS_NOT_FALSE");
includes(c.output_object_invariants,"REVIEWED_NOT_ESTABLISHED_IS_NOT_FALSE");
includes(c.output_object_invariants,"CONFLICT_IS_BLOCKED_NOT_FALSE");
includes(c.output_object_invariants,"PRIMARY_USE_ROLE_IS_CONTEXT_NOT_EFFICACY");
includes(c.output_object_invariants,"SCOPE_IS_PRESERVED_NOT_COLLAPSED");
includes(c.output_object_invariants,"LEGACY_PATHWAYS_ARE_NON_ADDITIVE");

eq(c.missingness_and_negative_contract.missing_current,"UNKNOWN_NOT_FALSE");
eq(c.missingness_and_negative_contract.reviewed_not_established,"UNKNOWN_NOT_FALSE");
eq(c.missingness_and_negative_contract.not_reviewed,"UNKNOWN_NOT_FALSE");
eq(c.missingness_and_negative_contract.evidence_insufficient,"UNKNOWN_NOT_FALSE");
eq(c.missingness_and_negative_contract.evidence_conflict,"BLOCKED_NOT_FALSE");
eq(c.missingness_and_negative_contract.explicit_false_requires_supported_boolean_false,true);
eq(c.missingness_and_negative_contract.absence_to_false,"PROHIBITED");

eq(c.input_contract.scope.preserve_exactly,true);
eq(c.input_contract.scope.collapse_cross_scope_truth,false);
eq(c.input_contract.scope.resolver_compatibility.existing_resolver_scope_complete,false);
eq(c.input_contract.scope.resolver_compatibility.gap_code,"SCOPE_TRANSPORT_GAP");
eq(c.input_contract.scope.resolver_compatibility.r3_action,"DO_NOT_MODIFY_HISTORICAL_RESOLVER");
eq(c.scope_resolution_contract.consumer_must_not_select_scope_implicitly,true);

eq(r2Corpus.bounded_shadow_corpus.adopted_moisturizer_products,10);
eq(r2Corpus.bounded_shadow_corpus.claim_established_products,6);
eq(r2Corpus.bounded_shadow_corpus.no_current_claim_products,4);
eq(r2Corpus.bounded_shadow_corpus.no_current_claim_semantics,"UNKNOWN_NOT_FALSE");
eq(r.frozen_live_authority_from_r2.resolved_moisturizer_subjects,10);
eq(r.frozen_live_authority_from_r2.governed_claim_true_products,6);
eq(r.frozen_live_authority_from_r2.no_current_claim_products,4);
eq(r.frozen_live_authority_from_r2.supported_false_products,0);

const barrierBlock=historicalMapper.match(/function mapBarrierSupport\(resolved\) \{[\s\S]*?\n\}/)?.[0]||"";
ok(barrierBlock.length>0,"historical barrier mapper block missing");
ok(barrierBlock.includes('const claims = supported(resolved, "barrier_support_claim");'),"historical mapper supported-only path drift");
eq(barrierBlock.includes("typed_value"),false,"historical mapper unexpectedly became boolean value-aware; R3 lineage must be reviewed");
eq(r.historical_compatibility_gaps.current_cross_category_mapper.barrier_mapper_boolean_value_aware,false);

const selectBlock=historicalResolver.match(/export const CURRENT_FACT_SELECT_V1 = `[\s\S]*?`\.trim\(\);/)?.[0]||"";
ok(selectBlock.length>0,"historical resolver SELECT block missing");
for(const field of ["f.market","f.region","f.locale","f.valid_from","f.valid_to"]) eq(selectBlock.includes(field),false,`historical resolver unexpectedly transports ${field}; R3 gap classification must be reviewed`);
eq(r.historical_compatibility_gaps.current_fact_resolver.scope_complete,false);
eq(r.historical_compatibility_gaps.current_fact_resolver.r3_action,"DO_NOT_MUTATE_HISTORICAL_RESOLVER");

eq(e.examples.length,11);
eq(e.fixture_boundary.all_examples_synthetic,true);
const stateCounts={};
const byId={};
for(const x of e.examples){
  eq(x.fixture_only,true,`${x.example_id}: fixture_only`);
  const out=mapBarrierSupportNonNumericPda(x.input);
  byId[x.example_id]=out;
  eq(out.signal.state,x.expected.signal_state,`${x.example_id}: signal state`);
  eq(out.signal.value,x.expected.signal_value,`${x.example_id}: signal value`);
  eq(out.coverage.state,x.expected.coverage_state,`${x.example_id}: coverage`);
  eq(out.context.primary_use_role.state,x.expected.context_state,`${x.example_id}: context state`);
  eq(out.uncertainty.reasons,x.expected.uncertainty_reasons,`${x.example_id}: uncertainty`);
  eq(out.scope_resolution.state,x.expected.scope_resolution_state,`${x.example_id}: scope resolution`);
  eq(out.numeric_estimate,null,`${x.example_id}: numeric`);
  eq(out.ordinal_magnitude,null,`${x.example_id}: ordinal`);
  eq(out.effect_strength,null,`${x.example_id}: effect strength`);
  eq(out.legacy_numeric_contribution,"PROHIBITED",`${x.example_id}: legacy additive boundary`);
  eq(out.production_consumption,"NO",`${x.example_id}: production boundary`);
  stateCounts[out.signal.state]=(stateCounts[out.signal.state]||0)+1;
}
eq(stateCounts,r.deterministic_fixture_replay.expected_state_counts);

eq(byId.supported_true_with_usage_role.signal.state,"GOVERNED_BARRIER_CLAIM_ESTABLISHED_TRUE");
eq(byId.supported_false_explicit_negative_with_usage_role.signal.state,"GOVERNED_BARRIER_CLAIM_ESTABLISHED_FALSE");
eq(byId.supported_false_explicit_negative_with_usage_role.signal.value,false);
eq(byId.missing_current_is_unknown_not_false.signal.state,"GOVERNED_BARRIER_CLAIM_UNKNOWN");
eq(byId.missing_current_is_unknown_not_false.signal.value,null);
eq(byId.evidence_insufficient_is_unknown.signal.state,"GOVERNED_BARRIER_CLAIM_UNKNOWN");
eq(byId.evidence_conflict_is_blocked.signal.state,"GOVERNED_BARRIER_CLAIM_BLOCKED");
eq(byId.disjoint_scope_opposite_values_require_context.scope_resolution.state,"CONTEXT_REQUIRED");
eq(byId.overlapping_scope_opposite_values_block.scope_resolution.state,"CONFLICT_BLOCKED");
eq(byId.non_moisturizer_not_applicable.signal.state,"NOT_APPLICABLE");

const trueWithRole=e.examples.find(x=>x.example_id==="supported_true_with_usage_role").input;
const trueWithoutRole=structuredClone(trueWithRole);
trueWithoutRole.primary_use_role_facts=[];
const mappedWithoutRole=mapBarrierSupportNonNumericPda(trueWithoutRole);
eq(mappedWithoutRole.signal.state,"GOVERNED_BARRIER_CLAIM_ESTABLISHED_TRUE","role missing must not change signal truth");
eq(mappedWithoutRole.signal.value,true,"role missing must not change signal value");
eq(mappedWithoutRole.coverage.state,"claim_only");
includes(mappedWithoutRole.uncertainty.reasons,"PRIMARY_USE_ROLE_MISSING");

eq(r.deterministic_fixture_replay.total_examples,11);
eq(r.primary_terminal_outcome,PRIMARY_TERMINAL_OUTCOME);
eq(r.decision,"V21_8H_R3_BARRIER_SUPPORT_NON_NUMERIC_PDA_CONTRACT_PASS");
eq(r.next_gate,"V2.1-8H-R4_BARRIER_SUPPORT_NON_NUMERIC_PDA_OFFLINE_SHADOW_REPLAY");
eq(r.execute_next_gate_now,false);

for(const [k,v] of Object.entries(c.explicit_non_actions)) eq(v,0,`${k}: must remain zero`);
for(const field of [
  "product_fact_current_delta","fact_instance_delta","confirmation_delta","registry_delta","migration_delta",
  "score_delta","ranking_delta","eligibility_delta","candidate_policy_delta","candidate_admission_delta",
  "public_response_delta","recommendation_behavior_delta"
]) eq(r.production_invariance_expected[field],0,field);
eq(r.production_invariance_expected.pda_production_consumption,"NO");
eq(r.production_invariance_expected.recommendation_activation,"NO");
eq(r.production_invariance_expected.public_activation,"NO");

console.log(JSON.stringify({
  version:"verify-v21-8h-r3-barrier-support-non-numeric-pda-contract",
  status:"PASS",
  assertions,
  stage:STAGE,
  axis_key:AXIS_KEY,
  examples:e.examples.length,
  state_counts:stateCounts,
  historical_mapper_false_value_blind_spot_confirmed:true,
  scope_transport_gap_confirmed:true,
  primary_terminal_outcome:PRIMARY_TERMINAL_OUTCOME,
  hashes:A.hashes
}));
