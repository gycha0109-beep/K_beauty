#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import {fileURLToPath} from "node:url";

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const P="evidence/product-fact-subject-coverage-v1/trust-p20-torriden-kr-identity-spf-pa-source-recovery-v1.json";
const stable=v=>Array.isArray(v)?v.map(stable):v&&typeof v==="object"?Object.fromEntries(Object.keys(v).sort().map(k=>[k,stable(v[k])])):v;
const canonical=v=>JSON.stringify(stable(v));
const digest=v=>crypto.createHash("sha256").update(typeof v==="string"?v:canonical(v)).digest("hex");

const x=JSON.parse(fs.readFileSync(path.join(ROOT,P),"utf8"));
const {research_content_sha256,...body}=x;
assert.equal(digest(body),research_content_sha256,"research content digest");
assert.equal(x.version,"trust-p20-torriden-kr-identity-spf-pa-source-recovery-v1");
assert.equal(x.stage,"TRUST-P20");
assert.equal(x.phase,"RESEARCH_ONLY_IDENTITY_FORMULATION_REVISION_AND_FACT_SOURCE_RECOVERY");
assert.equal(x.authority.source_main_sha,"2d0fc7007e8cc6c73f90e97b5880848ccf64f5fa");
assert.equal(x.target.product_id,"57e4a5ec-115d-4322-85a1-7976db669700");
assert.equal(x.target.prior_disposition,"IDENTITY_FORMULATION_REVISION_REVIEW_REQUIRED");
assert.equal(x.target.market,"KR");
assert.equal(x.production_prestate.subject_count,0);
assert.equal(x.production_prestate.current_count,0);
assert.deepEqual(x.production_prestate.global_counts,{subjects:22,sources:23,bindings:23,evidence:52,fact_instances:52,evidence_links:52,review_assignments:52,confirmations:52,current:52});
const legacy=x.first_party_sources.find(s=>s.role==="catalog_exact_legacy_display_name_identity_route");
const current=x.first_party_sources.find(s=>s.role==="current_kr_product_and_direct_fact_source");
const category=x.first_party_sources.find(s=>s.role==="current_identity_disambiguation");
assert.ok(legacy&&current&&category);
assert.equal(legacy.current_observation.presentation_name,"다이브인 워터리 모이스처 선크림 60ml");
assert.equal(legacy.current_observation.package_english_name,"DIVE IN Moisture Sun Cream");
assert.equal(current.current_observation.presentation_name,"다이브인 모이스처 선크림 60ml");
assert.equal(current.current_observation.package_english_name,"DIVE IN Moisture Sun Cream");
assert.equal(current.current_observation.package_direct_claim,"SPF50+ PA++++");
assert.equal(legacy.current_observation.detail_asset_namespace,current.current_observation.detail_asset_namespace);
assert.equal(category.current_observation.current_moisture_product,"다이브인 모이스처 선크림 60ml");
assert.equal(category.current_observation.distinct_mild_mineral_product,"다이브인 무기자차 마일드 선크림 60ml");
assert.equal(category.current_observation.cross_product_transfer_allowed,false);
assert.equal(x.identity_adjudication.status,"RESOLVED_FOR_PLAN");
assert.equal(x.identity_adjudication.mild_mineral_goods_transfer_allowed,false);
assert.equal(x.formulation_adjudication.status,"CURRENT_KR_PRESENTATION_RESOLVED_FOR_PLAN");
assert.equal(x.formulation_adjudication.historical_pre_upgrade_formulation_equivalence_asserted,false);
assert.equal(x.formulation_adjudication.cross_product_formula_transfer,false);
assert.equal(x.formulation_adjudication.fact_claim_transfer_required,false);
assert.equal(x.fact_recovery.spf_value.status,"RECOVERED_SUPPORTED");
assert.equal(x.fact_recovery.spf_value.raw_claim,"SPF50+");
assert.equal(x.fact_recovery.spf_value.value_number,50);
assert.deepEqual(x.fact_recovery.spf_value.qualifier,{plus_modifier:"plus"});
assert.equal(x.fact_recovery.uva_label.status,"RECOVERED_SUPPORTED");
assert.equal(x.fact_recovery.uva_label.raw_claim,"PA++++");
assert.equal(x.fact_recovery.uva_label.value_enum,"PA++++");
assert.equal(x.fact_recovery.spf_value.source_url,current.url);
assert.equal(x.fact_recovery.uva_label.source_url,current.url);
assert.equal(x.adjudication.result,"KR_CURRENT_IDENTITY_REVISION_AND_DIRECT_SPF_PA_SOURCE_RECOVERED");
assert.equal(x.adjudication.production_write_authorized,false);
assert.equal(x.adjudication.next_gate,"SEPARATE_DETERMINISTIC_HOSTED_ADOPTION_PLAN");
assert.equal(x.invariants.hosted_product_fact_writes,0);
assert.equal(x.invariants.direct_product_fact_dml,false);
assert.equal(x.invariants.cross_product_inference,false);
assert.equal(x.invariants.historical_pre_upgrade_formula_equivalence_asserted,false);
console.log(JSON.stringify({ok:true,stage:x.stage,result:x.adjudication.result,research_content_sha256},null,2));
