export function leadingNotices(bytes){
  const s=bytes.toString('utf8');
  const prefix=s.match(/^(?:\s|\/\/[^\n]*(?:\n|$)|\/\*[\s\S]*?\*\/)+/)?.[0]||'';
  const additional=[...s.slice(prefix.length).matchAll(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g)]
    .map(m=>m[0]).filter(t=>/copyright|license|public domain/i.test(t));
  return [prefix.trim(),...additional].filter(Boolean).join('\n\n');
}
