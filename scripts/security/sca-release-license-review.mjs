export function verifyPublicLicenseEvidence(record,read){
  assert.equal(record.schema,'bejewely.public-license-findings.v1');assert.equal(record.upstreamReplyRequired,false,'author reply is not an observed license condition');
  assert.equal(record.externalCommunicationAuthorized,false);assert.equal(record.packageRedistributionApproved,false);
  assert.deepEqual(record.sources.map(s=>s.file).sort(),evidenceNames.slice().sort(),'public evidence inventory mismatch');
  const texts={};
  for(const s of record.sources){assert.match(s.sha256,/^[a-f0-9]{64}$/);const b=read(s.file);
    assert.equal(b.length,s.bytes,'public evidence size mismatch');assert.equal(digest(b),s.sha256,'public evidence SHA mismatch');texts[s.file]=b.toString();}
  return texts;
}
// Pure preparation; this does not admit a candidate. Admission always calls the
// wrapper below, which compares every generated byte against the reviewed packet.
export function buildLicenseReviewResources(artifacts,files){
  assert.deepEqual(artifacts.map(a=>a.originalName).sort(),['braces','node-forge']);
  const notices=[];
  for(const name of ['braces','node-forge']){
    const expected=reference.installed.find(p=>p.name===name).fileSha256;
    assert.equal(digest(files[name].LICENSE),expected.LICENSE,'original license substitution');
    for(const [p,b] of Object.entries(files[name]).sort(([a],[b])=>a.localeCompare(b))){
      if(!p.endsWith('.js')||p.startsWith('dist/'))continue;
      const text=leadingNotices(b);
      if(!/copyright|license|public domain/i.test(text))continue;
      assert.equal(digest(b),expected[p],'notice-bearing source substitution: '+name+'/'+p);
      notices.push({package:name,path:p,fileSha256:digest(b),noticeSha256:digest(Buffer.from(text)),text});
    }
  }
  for(const r of embeddedReview){
    const n=notices.find(n=>n.package==='node-forge'&&n.path===r.path);
    assert.ok(n&&n.text.includes(r.marker),'embedded third-party notice missing: '+r.path);
  }
  const publicBytes=fs.readFileSync(new URL('../../security/release/sca-b6-public-license-findings.json',import.meta.url));
  const publicRecord=JSON.parse(publicBytes),publicTexts=verifyPublicLicenseEvidence(publicRecord,n=>fs.readFileSync(new URL('../../security/release/license-evidence/'+n,import.meta.url)));
  const report={schema:'bejewely.license-review.v1',status:'TECHNICAL_REVIEW_ONLY_LEGAL_HOLD',
    userAuthorizedReviewBasis:{braces:'MIT','node-forge':'BSD-3-Clause'},legalApproval:false,redistributionApproved:false,
    securityExceptionApproved:false,sourceEvidenceHead:reference.head,
    artifacts:artifacts.map(a=>({name:a.name,originalName:a.originalName,version:a.version,sha256:a.sha256,
      originalArchiveSha256:a.originalArchiveSha256,licenseSha256:a.licenseSha256})),
    embeddedReview,sourceNotices:notices.map(({text,...n})=>n),
    browserFiles:browserReference.browserBundles,
    browserNoticeDelivery:'All source notices and complete original LICENSE texts must accompany every redistributed browser bundle, including standalone copies. Minification is not evidence that notices survived.',
    buildToolScope:'webpack 4.44.1 and webpack-cli 3.3.12 are build tools, not automatically runtime components; cheap source maps are not a complete module inventory.',
    unbundledDependencyScope:'braces declares fill-range ^7.1.1; its separately installed transitive dependencies require their own LICENSEs and app SBOM. node-forge declares no runtime npm dependencies.',
    publicEvidenceSha256:digest(publicBytes),upstreamReplyRequired:false,
    internalAssuranceGaps:['Exact historical jscrypto/SJCL copied revision','Exact copied TweetNaCl revision','Complete historical line-by-line correspondence'],
    unresolved:['RSAES-OAEP full applicable BSD conditions assessment','Project owner final redistribution authorization',
      'Standalone bundle notice delivery and final artifact packaging review']};
  const notice='# Third-party notices — review packet, not release authorization\n\n'+
    'Review basis: braces MIT; node-forge BSD-3-Clause. Original dual-license file is retained intact; selecting a review basis does not relicense embedded works. No legal clearance or publication approval.\n\n'+
    ['braces','node-forge'].map(n=>'## '+n+' original LICENSE\n\n```text\n'+files[n].LICENSE.toString()+'\n```\n').join('\n')+
    notices.map(n=>'## '+n.package+'/'+n.path+'\n\nSource SHA256: '+n.fileSha256+'\n\n```text\n'+n.text+'\n```\n').join('\n')+
    '\n## Recovered public license evidence\n\nNo individual author reply is required by the observed permission texts. Exact historical revision gaps remain disclosed; no final legal or upload approval is conferred.\n\n'+
    Object.entries(publicTexts).map(([n,t])=>'### '+n+'\n\n```text\n'+t+'\n```\n').join('\n')+
    '\n## Unresolved rights review\n\n'+report.unresolved.map(x=>'- '+x).join('\n')+
    '\n\n## Internal provenance assurance gaps\n\n'+report.internalAssuranceGaps.map(x=>'- '+x).join('\n')+'\n';
  const components=artifacts.map(a=>({type:'library','bom-ref':a.name+'@'+a.version,name:a.name,version:a.version,
    hashes:[{alg:'SHA-256',content:a.sha256}],licenses:[{license:{id:a.originalName==='braces'?'MIT':'BSD-3-Clause'}}],
    properties:[{name:'bejewely:license-status',value:'USER_AUTHORIZED_REVIEW_BASIS_NOT_FINAL_LEGAL_ELECTION'},
      {name:'bejewely:original-name',value:a.originalName},{name:'bejewely:original-license-sha256',value:a.licenseSha256}]}));
  for(const r of embeddedReview)components.push({type:'library','bom-ref':'embedded:node-forge/'+r.path,name:r.name,
    hashes:[{alg:'SHA-256',content:notices.find(n=>n.package==='node-forge'&&n.path===r.path).fileSha256}],
    licenses:[{expression:r.license}],properties:[{name:'bejewely:license-review-status',value:r.status},{name:'bejewely:embedded-file',value:r.path}]});
  const sbom={bomFormat:'CycloneDX',specVersion:'1.6',version:1,components,
    dependencies:artifacts.map(a=>({ref:a.name+'@'+a.version,dependsOn:a.originalName==='node-forge'?embeddedReview.map(r=>'embedded:node-forge/'+r.path):[]}))};
  const resources={'THIRD-PARTY-NOTICES.md':Buffer.from(notice),'license-review.json':Buffer.from(JSON.stringify(report,null,2)+'\n'),
    'license-review-sbom.json':Buffer.from(JSON.stringify(sbom,null,2)+'\n'),'public-license-findings.json':publicBytes};
  return resources;
}
export function licenseReviewResources(artifacts,files){
  const resources=buildLicenseReviewResources(artifacts,files);
  for(const [n,b] of Object.entries(resources))assert.equal(digest(b),digest(fs.readFileSync(new URL('../../security/release/license-review/'+n,import.meta.url))),
    'generated license review differs from reviewed packet: '+n);
  return resources;
}
